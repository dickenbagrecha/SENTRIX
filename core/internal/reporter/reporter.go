// Package reporter formats vulnerability findings into actionable developer reports.
package reporter

import (
	"bytes"
	"fmt"
	"text/template"
	"time"

	"sentrix/core/pkg/models"
)

const markdownReportTemplate = `# [SENTRIX-FINDING] {{ .Title }}

| Field | Value |
| :--- | :--- |
| **Finding ID** | ` + "`{{ .FindingID }}`" + ` |
| **Attack Category** | **{{ .Category }}** |
| **Severity** | **{{ .Severity }}** |
| **Confidence** | {{ .Confidence }} |
| **Current State** | **{{ .State }}** |
| **Assigned Developer** | {{ if .AssignedDeveloper }}{{ .AssignedDeveloper }}{{ else }}*Unassigned*{{ end }} |
| **Affected Endpoint** | ` + "`{{ .AffectedEndpoint }}`" + ` |
| **Affected Component**| ` + "`{{ .AffectedComponent }}`" + ` |
| **Detected At** | {{ .DetectedAt.Format "2006-01-02 15:04:05 UTC" }} |
| **Regression Test ID** | ` + "`{{ .RegressionTestID }}`" + ` |

---

### 1. Vulnerability Description
{{ .Description }}

---

### 2. Technical Evidence
- **Request Method & Path:** ` + "`{{ .TechnicalEvidence.RequestMethod }} {{ .TechnicalEvidence.RequestURL }}`" + `
- **Response Status Code:** ` + "`{{ .TechnicalEvidence.ResponseStatus }}`" + `
- **Latency:** ` + "`{{ .TechnicalEvidence.LatencyMs }}ms`" + `
{{ if .TechnicalEvidence.CanaryMatched }}- **Canary Token Matched:** ` + "`{{ .TechnicalEvidence.CanaryMatched }}`" + `{{ end }}

#### Request Payload:
` + "```http" + `
{{ if .TechnicalEvidence.RequestBody }}{{ .TechnicalEvidence.RequestBody }}{{ else }}[No Request Body]{{ end }}
` + "```" + `

#### Response Sample:
` + "```http" + `
{{ if .TechnicalEvidence.ResponseBodySample }}{{ .TechnicalEvidence.ResponseBodySample }}{{ else }}[Empty Response]{{ end }}
` + "```" + `

---

### 3. Step-by-Step Reproduction Instructions
Execute the following automated reproduction command against the authorized staging instance:
` + "```bash" + `
{{ .ReproductionSteps }}
` + "```" + `

---

### 4. Business & Security Impact
{{ .BusinessImpact }}

---

### 5. Recommended Actionable Remediation
{{ .RecommendedRemediation }}

---

### 6. Developer Regression Testing Verification
Once the fix is merged into the staging branch, execute the following regression verification command:
` + "```bash" + `
sentrixctl test --regression {{ .RegressionTestID }} --target staging.vlookup.local
` + "```" + `

---
*Report generated by SENTRIX Security Auditing Platform on {{ .GeneratedAt.Format "2006-01-02 15:04:05 UTC" }}*
`

type reportView struct {
	*models.VulnerabilityFinding
	GeneratedAt time.Time
}

// GenerateMarkdown creates an engineering-grade report for a single vulnerability finding.
func GenerateMarkdown(finding *models.VulnerabilityFinding) (string, error) {
	tmpl, err := template.New("markdownReport").Parse(markdownReportTemplate)
	if err != nil {
		return "", fmt.Errorf("failed to parse report template: %w", err)
	}

	view := reportView{
		VulnerabilityFinding: finding,
		GeneratedAt:          time.Now().UTC(),
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, view); err != nil {
		return "", fmt.Errorf("failed to render markdown report: %w", err)
	}

	return buf.String(), nil
}
